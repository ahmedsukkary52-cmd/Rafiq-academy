/// حالة تحميل عامة لأي قسم بيانات بيتجاب من السيرفر (عمليات قراءة GET).
/// بتُستخدم في كل الـ Blocs عشان كل قسم في الشاشة (بروفايل، قائمة، تقرير...)
/// يكون له دورة حياة مستقلة عن باقي الأقسام.
enum SectionStatus { initial, loading, loaded, error }

/// حالة عامة لأي عملية إرسال/تعديل (POST/PUT) زي تقديم طلب استئذان،
/// تسجيل حضور، إرسال تكليف، الرد على شكوى...إلخ.
///
/// منفصلة عمداً عن [SectionStatus] لأن عملية الإرسال غالباً بتتحكم في
/// زرار واحد بس (مثلاً "إرسال") وميصحش تأثر على حالة تحميل باقي الشاشة.
enum SubmissionStatus { idle, submitting, success, error }
